"""Write the public Umami Website ID into the static site's analytics config."""

import json
import os
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "assets" / "js" / "analytics-config.js"
UUID = re.compile(r"[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}\Z")


def build() -> None:
    website_id = os.environ.get("UMAMI_WEBSITE_ID", "").strip()
    if website_id and not UUID.fullmatch(website_id):
        raise ValueError("UMAMI_WEBSITE_ID must be a UUID from Umami's website settings")
    TARGET.write_text(
        "// Generated by tools/build_analytics_config.py. Empty ID keeps analytics disabled.\n"
        f"window.siteAnalyticsConfig = {{ websiteId: {json.dumps(website_id)} }};\n",
        encoding="utf-8",
    )
    print("Analytics configuration: " + ("ready for review" if website_id else "disabled"))


if __name__ == "__main__":
    build()
